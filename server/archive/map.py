from rapidfuzz import fuzz
import re


def normalize(text):
    text = text.lower().strip()
    text = re.sub(r"[^\w\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text


def map_category(input_string, start_threshold=100, min_threshold=70):
    if not input_string:
        return {"ro": "other", "en": "Other", "ru": "Другое"}

    normalized_input = normalize(input_string)
    threshold = start_threshold

    while threshold >= min_threshold:
        for cat in categories:
            for key in ["ro", "en", "ru"]:
                score = max(
                    fuzz.ratio(normalized_input, normalize(cat[key])),
                    fuzz.token_sort_ratio(normalized_input, normalize(cat[key])),
                    fuzz.partial_token_sort_ratio(
                        normalized_input, normalize(cat[key])
                    ),
                )
                if score >= threshold:
                    return {k: v for k, v in cat.items() if k in ["ro", "en", "ru"]}
        threshold -= 1

    return {"ro": "other", "en": "Other", "ru": "Другое"}


